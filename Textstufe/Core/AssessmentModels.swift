import Foundation

/// The indicative CEFR reading level. No level is an official certification.
enum CEFRLevel: String, CaseIterable, Codable, Sendable, Comparable {
    case a1 = "A1", a2 = "A2", b1 = "B1", b2 = "B2", c1 = "C1", c2 = "C2"

    private var order: Int { Self.allCases.firstIndex(of: self)! }
    static func < (lhs: Self, rhs: Self) -> Bool { lhs.order < rhs.order }
}

enum AssessmentState: Sendable, Equatable {
    case ready
    case tooShort
    case notGerman
    case empty
}

struct WordObservation: Sendable, Equatable {
    let surface: String
    let lemma: String?

    init(_ surface: String, lemma: String? = nil) {
        self.surface = surface
        self.lemma = lemma
    }
}

/// Platform-independent metrics; generated by the Apple NaturalLanguage adapter.
struct TextFeatures: Sendable, Equatable {
    let words: [WordObservation]
    let sentenceWordCounts: [Int]
    let germanConfidence: Double?
    let detectedLanguageIsGerman: Bool

    init(
        words: [WordObservation],
        sentenceWordCounts: [Int],
        germanConfidence: Double? = nil,
        detectedLanguageIsGerman: Bool = true
    ) {
        self.words = words
        self.sentenceWordCounts = sentenceWordCounts
        self.germanConfidence = germanConfidence
        self.detectedLanguageIsGerman = detectedLanguageIsGerman
    }
}

/// Explanations shown below a result. The raw value is the localization key.
enum AssessmentInsight: String, CaseIterable, Sendable {
    case longSentences
    case shortSentences
    case manyLongWords
    case limitedVocabulary
    case commonVocabulary
    case mixedStructure

    var localizationKey: String { "insight.\(rawValue)" }
}

/// The six features used by the ZIX regression, in model order.
struct ZixFeatureVector: Sendable, Equatable {
    let sentenceLengthMean: Double
    let rix: Double
    let vocabularyA1: Double
    let vocabularyA2: Double
    let vocabularyB1: Double
    let commonWordScore: Double

    var values: [Double] {
        [sentenceLengthMean, rix, vocabularyA1, vocabularyA2, vocabularyB1, commonWordScore]
    }
}

struct Assessment: Sendable, Equatable {
    let state: AssessmentState
    let level: CEFRLevel?
    /// The neighbouring level when the score sits close to a band boundary.
    let alternateLevel: CEFRLevel?
    /// ZIX understandability score, -10 (hard) to +10 (easy).
    let zixScore: Double?
    let wordCount: Int
    let sentenceCount: Int
    let wordsPerSentence: Double
    let longWordShare: Double
    /// Share of words found in the A1–B1 reference vocabulary (B1 is the broadest list).
    let vocabularyCoverage: Double
    let commonWordScore: Double
    let insights: [AssessmentInsight]
    let challengingWords: [String]
    let features: ZixFeatureVector?

    var isUncertain: Bool { alternateLevel != nil }

    static func placeholder(state: AssessmentState, features: TextFeatures) -> Assessment {
        let count = features.words.count
        let sentences = features.sentenceWordCounts.filter { $0 > 0 }.count
        return Assessment(
            state: state,
            level: nil,
            alternateLevel: nil,
            zixScore: nil,
            wordCount: count,
            sentenceCount: sentences,
            wordsPerSentence: sentences > 0 ? Double(count) / Double(sentences) : 0,
            longWordShare: 0,
            vocabularyCoverage: 0,
            commonWordScore: 0,
            insights: [],
            challengingWords: [],
            features: nil
        )
    }
}
